/* =========================================================
   BUILD THE TABLE
   ========================================================= */

function buildTable() {

    const table = document.getElementById("dubTable");

    if (!table) {
        console.error("Could not find #dubTable");
        return;
    }

    table.innerHTML = "";


    dubs.forEach(function (dub, index) {

        /*
         * MAIN ROW
         */

        const row = document.createElement("tr");

        row.className = "main-row";


        /* Language */

        const languageCell =
            document.createElement("td");

        languageCell.className =
            "language-cell";

        languageCell.textContent =
            dub.language;


        /* Title */

        const titleCell =
            document.createElement("td");

        titleCell.className =
            "title-cell";

        titleCell.textContent =
            dub.title;


        /* Versions */

        const versionsCell =
            document.createElement("td");

        versionsCell.className =
            "versions-cell";


        if (dub.versions.length > 1) {

            const versionButton =
                document.createElement("button");

            versionButton.type = "button";

            versionButton.className =
                "version-button";

            versionButton.textContent =
                "▶ Show versions";

            versionButton.addEventListener(
                "click",
                function () {
                    toggleVersions(
                        index,
                        versionButton
                    );
                }
            );

            versionsCell.appendChild(
                versionButton
            );

        } else {

            versionsCell.textContent = "—";

        }


        /* Play */

        const playCell =
            document.createElement("td");

        playCell.className =
            "play-cell";


        const playButton =
            document.createElement("button");

        playButton.type = "button";

        playButton.className =
            "play-button";

        playButton.textContent =
            "▶ Play";


        playButton.addEventListener(
            "click",
            function () {

                /*
                 * The first entry is the version
                 * selected when pressing the main
                 * Play button.
                 */

                const version =
                    dub.versions[0];

                playVersion(
                    version,
                    dub
                );

            }
        );


        playCell.appendChild(
            playButton
        );


        /*
         * Assemble main row
         */

        row.appendChild(languageCell);

        row.appendChild(titleCell);

        row.appendChild(versionsCell);

        row.appendChild(playCell);


        table.appendChild(row);


        /*
         * VERSION ROW
         */

        if (dub.versions.length > 1) {

            const versionRow =
                document.createElement("tr");

            versionRow.className =
                "version-row";

            versionRow.id =
                "versions-" + index;


            const versionCell =
                document.createElement("td");

            versionCell.colSpan = 4;

            versionCell.className =
                "version-list-cell";


            const versionList =
                document.createElement("div");

            versionList.className =
                "version-list";


            dub.versions.forEach(
                function (version) {

                    const item =
                        document.createElement("div");

                    item.className =
                        "version-item";


                    const info =
                        document.createElement("div");

                    info.className =
                        "version-info";


                    const name =
                        document.createElement("strong");

                    name.textContent =
                        version.name;


                    info.appendChild(name);


                    if (version.studio) {

                        const studio =
                            document.createElement("span");

                        studio.className =
                            "version-studio";

                        studio.textContent =
                            " — " +
                            version.studio;

                        info.appendChild(studio);
                    }


                    const button =
                        document.createElement("button");

                    button.type = "button";

                    button.className =
                        "play-button";

                    button.textContent =
                        "▶ Play";


                    button.addEventListener(
                        "click",
                        function () {

                            playVersion(
                                version,
                                dub
                            );

                        }
                    );


                    item.appendChild(info);

                    item.appendChild(button);

                    versionList.appendChild(item);

                }
            );


            versionCell.appendChild(
                versionList
            );

            versionRow.appendChild(
                versionCell
            );

            table.appendChild(
                versionRow
            );

        }

    });


    /*
     * Update statistics
     */

    document.getElementById(
        "dubCount"
    ).textContent = dubs.length;


    document.getElementById(
        "languageCount"
    ).textContent = dubs.length;

}


/* =========================================================
   VERSION TOGGLE
   ========================================================= */

function toggleVersions(index, button) {

    const row =
        document.getElementById(
            "versions-" + index
        );


    if (!row) {
        return;
    }


    const isOpen =
        row.classList.contains("open");


    if (isOpen) {

        row.classList.remove("open");

        button.textContent =
            "▶ Show versions";

    } else {

        row.classList.add("open");

        button.textContent =
            "▼ Hide versions";

    }

}


/* =========================================================
   PLAY VERSION
   ========================================================= */

function playVersion(version, dub) {

    const player =
        document.getElementById(
            "videoPlayer"
        );


    const nowPlaying =
        document.getElementById(
            "nowPlaying"
        );


    /*
     * We deliberately don't invent video URLs.
     *
     * Until an actual video URL is entered for a
     * version, the player stays on the current video.
     */

    if (version.video) {

        player.src =
            version.video;

    }


    nowPlaying.textContent =
        dub.language +
        " — " +
        version.name;


    document.querySelector(
        ".player-section"
    ).scrollIntoView({
        behavior: "smooth",
        block: "start"
    });

}


/* =========================================================
   INFORMATION BUTTON
   ========================================================= */

function setupInformationButton() {

    const button =
        document.getElementById(
            "infoButton"
        );


    const info =
        document.getElementById(
            "archiveInfo"
        );


    if (!button || !info) {
        return;
    }


    button.addEventListener(
        "click",
        function () {

            const isHidden =
                info.hidden;


            info.hidden =
                !isHidden;


            button.textContent =
                isHidden
                    ? "▲ Hide information"
                    : "▼ Show more information";

        }
    );

}


